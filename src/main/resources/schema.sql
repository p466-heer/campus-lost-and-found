CREATE TABLE IF NOT EXISTS "FOUND_ITEM" (
                                            ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            NAME VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(500) NOT NULL,
    FOUND_LOCATION VARCHAR(200) NOT NULL,
    DATE_REPORTED TIMESTAMP,
    REPORTED_BY_USER_ID BIGINT
    );

CREATE TABLE IF NOT EXISTS "APP_USER" (
                                          ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          NAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(255) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL,
    ROLE VARCHAR(20) NOT NULL DEFAULT 'STUDENT'
    );

CREATE TABLE IF NOT EXISTS "ITEM_CLAIM" (
                                            ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            FOUND_ITEM_ID BIGINT NOT NULL,
                                            STUDENT_ID BIGINT NOT NULL,
                                            EXPLANATION VARCHAR(1000) NOT NULL,
    STATUS VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    DATE_SUBMITTED TIMESTAMP NOT NULL,
    FOREIGN KEY (FOUND_ITEM_ID) REFERENCES "FOUND_ITEM"(ID),
    FOREIGN KEY (STUDENT_ID) REFERENCES "APP_USER"(ID)
    );
